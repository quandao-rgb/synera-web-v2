export function displayLabel(value: unknown) {
  const text = value === null || value === undefined ? '' : String(value);
  return terms[text] || statusLabels[text] || userRoleLabel(text);
}
export function dateLabel(value: unknown, time = false) {
  if (!value) return '—';
  const text = String(value);
  const date = new Date(/^\d{4}-\d{2}-\d{2}$/.test(text) ? text + 'T00:00:00+07:00' : text);
  if (!Number.isFinite(date.getTime())) return text;
  return time
    ? date.toLocaleString('vi-VN', { timeZone: 'Asia/Ho_Chi_Minh' })
    : date.toLocaleDateString('vi-VN', { timeZone: 'Asia/Ho_Chi_Minh' });
}
